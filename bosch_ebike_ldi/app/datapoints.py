"""
Bosch smart-system datapoints: names, decoding, and what this add-on reads.

The table (datapoints.json) is generated by scripts/build_datapoints.py from
the implementation handoff. Each datapoint has a "kind" telling how its
protobuf wrapper is decoded:

  uint / sint     field 1, unsigned or ZigZag-signed varint, ÷ factor
  bool / string   field 1
  uint[] / ...    repeated field 1
  struct          a structured message: all fields kept as a dict
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, NamedTuple

import protowire

TABLE_PATH = Path(__file__).with_name("datapoints.json")


class Datapoint(NamedTuple):
    id: int
    component: str
    name: str
    kind: str
    factor: int = 1
    readable: bool = True
    unit: str | None = None
    struct: str | None = None

    @property
    def label(self) -> str:
        return f"{self.component}.{self.name}"


def load_table(path: Path = TABLE_PATH) -> dict[int, Datapoint]:
    raw = json.loads(path.read_text(encoding="utf-8"))
    return {int(key, 16): Datapoint(id=int(key, 16), **entry) for key, entry in raw.items()}


def decode_value(dp: Datapoint | None, body: bytes) -> Any:
    """Decode one datapoint payload. Unknown datapoints decode generically.

    Returns None for an empty payload (absent value), never a fake zero.
    """
    if not body:
        # An all-default message is zero bytes on the wire: that's a value ({}).
        return {} if dp is not None and dp.kind == "struct" else None
    if dp is None or dp.kind == "struct":
        return protowire.to_plain(body)
    values = []
    for f in protowire.decode(body):
        if f.number != 1:
            continue
        if isinstance(f.value, (bytes, bytearray)) and dp.kind.rstrip("[]") != "string":
            values += _unpack_varints(bytes(f.value))      # packed repeated numbers
        else:
            values.append(f.value)
    converted = [_convert(dp, v) for v in values]
    if dp.kind.endswith("[]"):
        return converted
    return converted[-1] if converted else None   # last value wins (protobuf)


def _unpack_varints(data: bytes) -> list[int]:
    out, value, shift = [], 0, 0
    for byte in data:
        value |= (byte & 0x7F) << shift
        shift += 7
        if not byte & 0x80:
            out.append(value)
            value, shift = 0, 0
    return out


def _convert(dp: Datapoint, value):
    base = dp.kind.rstrip("[]")
    if base == "string":
        return value.decode("utf-8", errors="replace")
    if base == "bool":
        return bool(value)
    if base == "sint":
        value = protowire.zigzag(value)
    if base in ("uint", "sint") and dp.factor != 1:
        return value / dp.factor
    return value


